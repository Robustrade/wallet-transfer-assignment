// Package http provides the transport layer: thin HTTP handlers that validate
// requests, invoke the service layer and map domain results/errors onto HTTP
// responses. It contains no business logic.
package http

import (
	"encoding/json"
	"net/http"

	"github.com/Robustrade/wallet-transfer-assignment/internal/domain"
)

// createTransferRequest is the wire model for POST /api/v1/transfers.
type createTransferRequest struct {
	IdempotencyKey string `json:"idempotencyKey"`
	FromWalletID   string `json:"fromWalletId"`
	ToWalletID     string `json:"toWalletId"`
	Amount         int64  `json:"amount"`
}

// toDomain maps the wire model to the service-layer request type.
func (r createTransferRequest) toDomain() domain.TransferRequest {
	return domain.TransferRequest{
		IdempotencyKey: r.IdempotencyKey,
		FromWalletID:   r.FromWalletID,
		ToWalletID:     r.ToWalletID,
		Amount:         r.Amount,
	}
}

// transferResponse is the wire model returned for a transfer.
type transferResponse struct {
	ID             string `json:"id"`
	IdempotencyKey string `json:"idempotencyKey"`
	FromWalletID   string `json:"fromWalletId"`
	ToWalletID     string `json:"toWalletId"`
	Amount         int64  `json:"amount"`
	Currency       string `json:"currency"`
	Status         string `json:"status"`
	FailureReason  string `json:"failureReason,omitempty"`
	CreatedAt      string `json:"createdAt"`
	UpdatedAt      string `json:"updatedAt"`
}

func newTransferResponse(t *domain.Transfer) transferResponse {
	return transferResponse{
		ID:             t.ID,
		IdempotencyKey: t.IdempotencyKey,
		FromWalletID:   t.FromWalletID,
		ToWalletID:     t.ToWalletID,
		Amount:         t.Amount,
		Currency:       t.Currency,
		Status:         string(t.Status),
		FailureReason:  t.FailureReason,
		CreatedAt:      t.CreatedAt.Format(timeLayout),
		UpdatedAt:      t.UpdatedAt.Format(timeLayout),
	}
}

// createWalletRequest is the wire model for POST /api/v1/wallets. The wallet id
// is generated by the server, so it is not part of the request.
type createWalletRequest struct {
	OpeningBalance int64  `json:"openingBalance"`
	Currency       string `json:"currency"`
}

// walletResponse is the wire model returned for a wallet.
type walletResponse struct {
	ID        string `json:"id"`
	Balance   int64  `json:"balance"`
	Currency  string `json:"currency"`
	CreatedAt string `json:"createdAt"`
	UpdatedAt string `json:"updatedAt"`
}

func newWalletResponse(w *domain.Wallet) walletResponse {
	return walletResponse{
		ID:        w.ID,
		Balance:   w.Balance,
		Currency:  w.Currency,
		CreatedAt: w.CreatedAt.Format(timeLayout),
		UpdatedAt: w.UpdatedAt.Format(timeLayout),
	}
}

// ledgerEntryResponse is the wire model for a single ledger line.
type ledgerEntryResponse struct {
	ID         int64  `json:"id"`
	TransferID string `json:"transferId"`
	WalletID   string `json:"walletId"`
	Type       string `json:"type"`
	Amount     int64  `json:"amount"`
	CreatedAt  string `json:"createdAt"`
}

// ledgerListResponse wraps the ledger collection so the payload can grow
// (pagination metadata, etc.) without breaking clients.
type ledgerListResponse struct {
	WalletID string                `json:"walletId"`
	Entries  []ledgerEntryResponse `json:"entries"`
}

func newLedgerListResponse(walletID string, entries []domain.LedgerEntry) ledgerListResponse {
	out := ledgerListResponse{WalletID: walletID, Entries: make([]ledgerEntryResponse, 0, len(entries))}
	for _, e := range entries {
		out.Entries = append(out.Entries, ledgerEntryResponse{
			ID:         e.ID,
			TransferID: e.TransferID,
			WalletID:   e.WalletID,
			Type:       string(e.Type),
			Amount:     e.Amount,
			CreatedAt:  e.CreatedAt.Format(timeLayout),
		})
	}
	return out
}

// errorResponse is the uniform error envelope returned to clients.
type errorResponse struct {
	Error errorBody `json:"error"`
}

type errorBody struct {
	Code    string `json:"code"`
	Message string `json:"message"`
	Field   string `json:"field,omitempty"`
}

// writeJSON encodes v as JSON with the given status code.
func writeJSON(w http.ResponseWriter, status int, v any) {
	w.Header().Set("Content-Type", "application/json; charset=utf-8")
	w.WriteHeader(status)
	if v != nil {
		_ = json.NewEncoder(w).Encode(v)
	}
}
